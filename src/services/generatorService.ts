  private analyzeProjectContext(): ProjectContext {
    const pkgPath = path.join(this.cwd, 'package.json');
    let projectName = 'RepoPilot';
    let description = 'Autonomous Repository Co-Pilot';
    const dependencies: string[] = [];

    if (fs.existsSync(pkgPath)) {
      try {
        const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
        if (pkg.displayName || pkg.name) {
          projectName = pkg.displayName || pkg.name;
        }
        if (pkg.description) {
          description = pkg.description;
        }
        if (pkg.dependencies) {
          dependencies.push(...Object.keys(pkg.dependencies));
        }
      } catch {
        // Fallback
      }
    }

    const reqPath = path.join(this.cwd, 'requirements.txt');
    if (fs.existsSync(reqPath)) {
      try {
        const content = fs.readFileSync(reqPath, 'utf8');
        content.split('\n').forEach((l) => {
          const clean = l.split(/[=<>#;]/)[0].trim();
          if (clean && !clean.startsWith('-')) {
            dependencies.push(clean);
          }
        });
      } catch {
        // Fallback
      }
    }

    const backendRoutes: string[] = [];
    const hasDocker = fs.existsSync(path.join(this.cwd, 'Dockerfile'));
    const hasPlaywright = dependencies.some((d) => d.includes('playwright'));
    const hasGeminiOrGroq = dependencies.some((d) => d.includes('groq') || d.includes('gemini') || d.includes('google'));

    return {
      projectName,
      description,
      backendRoutes,
      dependencies,
      hasDocker,
      hasPlaywright,
      hasGeminiOrGroq
    };
  }
