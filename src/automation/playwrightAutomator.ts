import * as fs from 'fs';
import * as path from 'path';
import { PortalSubmissionSchema, type PortalSubmission, validateWithSchema } from '../verification/schemas';
import { GitService } from '../services/gitService';

export interface WebEndpointAudit {
  url: string;
  isAccessible: boolean;
  statusCode?: number;
  responseTimeMs?: number;
  title?: string;
  error?: string;
}

export class PlaywrightAutomator {
  private workspaceRoot: string;

  constructor(workspaceRoot: string) {
    this.workspaceRoot = workspaceRoot;
  }

  /**
   * Scrapes and checks if an external web demo or local dev server is alive.
   */
  public async scrapeEndpoint(targetUrl: string): Promise<WebEndpointAudit> {
    const startTime = Date.now();
    try {
      const response = await fetch(targetUrl, {
        method: 'GET',
        headers: { 'User-Agent': 'RepoPilot-Automator/0.1.0' },
        signal: AbortSignal.timeout(6000)
      });
      const responseTimeMs = Date.now() - startTime;
      const htmlText = await response.text();
      const titleMatch = htmlText.match(/<title>([^<]*)<\/title>/i);
      const title = titleMatch ? titleMatch[1].trim() : undefined;

      return {
        url: targetUrl,
        isAccessible: response.ok,
        statusCode: response.status,
        responseTimeMs,
        title
      };
    } catch (err: unknown) {
      return {
        url: targetUrl,
        isAccessible: false,
        responseTimeMs: Date.now() - startTime,
        error: err instanceof Error ? err.message : String(err)
      };
    }
  }

  /**
   * Synthesizes and validates a hackathon submission payload using Zod.
   */
  public generateSubmissionPayload(): { payload: PortalSubmission; jsonPath: string; previewPath: string } {
    const gitService = new GitService(this.workspaceRoot);
    const remoteUrl = gitService.getRemoteUrl() || 'https://github.com/anubhabmondal496-coder/RepoPilot.git';
    const pkgJsonPath = path.join(this.workspaceRoot, 'package.json');
    let title = 'RepoPilot';
    let tagline = 'Autonomous developer copilot for health, API contracts, and hackathon defense';
    let description = 'RepoPilot is an autonomous VS Code extension and CLI orchestration platform featuring a Dual-Mode Hybrid Engine (Preview vs Turbo Mode).';
    const techStack: string[] = ['TypeScript', 'Node.js', 'VS Code API', 'Google Gemini 2.5/3.8 Flash', 'Groq Llama-3.3-70B', 'Playwright'];

    if (fs.existsSync(pkgJsonPath)) {
      try {
        const pkg = JSON.parse(fs.readFileSync(pkgJsonPath, 'utf8'));
        if (pkg.name) {
          title = pkg.displayName || pkg.name;
        }
        if (pkg.description) {
          tagline = pkg.description.slice(0, 120);
          description = pkg.description;
        }
      } catch {
        // Fallback
      }
    }

    const rawData = {
      projectName: title,
      tagline,
      description: `${description} Includes automated AST-free API route reconciliation, security scanning, semantic Git commits, and judge defense synthesis.`,
      repositoryUrl: remoteUrl,
      demoUrl: `https://gitdiagram.com/${remoteUrl.replace(/^https?:\/\/github\.com\//, '').replace(/\.git$/, '')}`,
      videoUrl: '',
      tracks: ['Developer Tools', 'AI & Automation', 'Productivity'],
      techStack,
      builtWith: ['TypeScript', 'Gemini AI', 'Groq Llama', 'Playwright', 'Octokit'],
      submittedAt: new Date().toISOString()
    };

    const validation = validateWithSchema(PortalSubmissionSchema, rawData, rawData as PortalSubmission);
    const payload = validation.data;

    const docsDir = path.join(this.workspaceRoot, 'docs');
    if (!fs.existsSync(docsDir)) {
      fs.mkdirSync(docsDir, { recursive: true });
    }

    const jsonPath = path.join(docsDir, 'PORTAL_SUBMISSION.json');
    fs.writeFileSync(jsonPath, JSON.stringify(payload, null, 2), 'utf8');

    const previewPath = path.join(docsDir, 'SUBMISSION_PREVIEW.md');
    const mdContent = `# 🏆 Hackathon Portal Submission Summary

> **Generated automatically by RepoPilot Playwright Automator**  
> Timestamp: \`${payload.submittedAt}\`  
> Validation: **${validation.success ? '✅ PASSED (Zod Schemas Verified)' : '⚠️ WARNING (Field Adjustments Needed)'}**

---

### 1. General Project Details
- **Project Name:** ${payload.projectName}
- **Tagline:** ${payload.tagline}
- **Repository URL:** [${payload.repositoryUrl}](${payload.repositoryUrl})
- **Interactive Architecture Demo:** [GitDiagram](${payload.demoUrl})

### 2. Elevator Pitch & Description
${payload.description}

### 3. Tech Stack & Integrations
${payload.techStack.map((tech) => `- **${tech}**`).join('\n')}

### 4. Eligible Tracks
${payload.tracks.map((t) => `- 🎯 ${t}`).join('\n')}

---
*Generated by RepoPilot Autonomous Engine.*
`;
    fs.writeFileSync(previewPath, mdContent, 'utf8');

    // Generate Playwright E2E automation script
    this.generatePlaywrightTestScript(payload);

    return { payload, jsonPath, previewPath };
  }

  /**
   * Generates a reusable Playwright spec script (tests/portal_submission.spec.ts)
   */
  public generatePlaywrightTestScript(payload: PortalSubmission): string {
    const testsDir = path.join(this.workspaceRoot, 'tests');
    if (!fs.existsSync(testsDir)) {
      fs.mkdirSync(testsDir, { recursive: true });
    }
    const specPath = path.join(testsDir, 'portal_submission.spec.ts');
    const specContent = `import { test, expect } from '@playwright/test';

/**
 * RepoPilot Automated Submission & Health Verification Spec
 * Generated automatically by PlaywrightAutomator
 */
test.describe('RepoPilot Submission & Portal Smoke Tests', () => {
  const payload = ${JSON.stringify(payload, null, 2)};

  test('Verify repository URL is accessible', async ({ request }) => {
    const response = await request.get(payload.repositoryUrl);
    expect(response.status()).toBeLessThan(400);
  });

  test('Verify interactive architecture visualizer', async ({ page }) => {
    if (payload.demoUrl) {
      await page.goto(payload.demoUrl, { timeout: 15000 });
      await expect(page).toHaveTitle(/Diagram|GitHub|RepoPilot/i);
    }
  });

  test('Verify submission form fields schema integrity', async () => {
    expect(payload.projectName).toBeTruthy();
    expect(payload.tagline.length).toBeLessThanOrEqual(120);
    expect(payload.techStack.length).toBeGreaterThan(0);
  });
});
`;
    fs.writeFileSync(specPath, specContent, 'utf8');
    return specPath;
  }
}
